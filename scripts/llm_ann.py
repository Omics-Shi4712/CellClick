"""
LLM-assisted cell type annotation helpers.

This module keeps LLM use outside the deterministic scoring path. CellClick
calculates COSG marker genes and marker gene scores first, then these helpers
package the score table and marker evidence for an LLM to interpret.
"""

import json
import re

import pandas as pd


MARKER_GENE_SCORE_ALGORITHM_DESCRIPTION = """
CellClick Cell Identification algorithm:
1. Marker genes for the selected cell cluster are identified by COSG. COSG
   provides an expression specificity score for each candidate marker gene.
2. Reference marker genes are collected from marker databases such as
   CellMarker 2.0, singleCellBase, and CellStar. For each reference cell type,
   CellClick stores a marker gene confidence score (MGC) as geneWeight.
3. For a candidate reference cell type r and selected cluster c, CellClick
   compares the COSG marker set Gc with the reference marker set Gr. Genes in
   the overlap Gc,r = Gc intersect Gr provide the direct evidence.
4. In the current implementation, the marker gene score for each reference cell
   type is calculated as:
      score(r|c) =
        sum_over_overlap(MGC(g,r))
        *
        sum_over_overlap(COSG_score(g,c) / sum_COSG_scores_for_used_genes)
   where the first term reflects published/reference marker support and the
   second term reflects how specifically the overlapping genes mark the current
   cluster according to COSG.
5. Higher scores indicate stronger support for annotating the selected cluster
   as the corresponding reference cell type. The LLM should treat the score as
   ranking evidence, not as a calibrated probability.
"""

CELL_SCORE_ALGORITHM_DESCRIPTION = """
CellClick Reference Comparison cell score algorithm:
1. Given a marker gene set Gc for a defined/query cell type Cc, and a marker
   gene set Gt obtained by COSG for a reference cell type Ct, CellClick
   calculates CellScore(ci | Cc, Ct, Gc, Gt) for each cell ci from Cc to
   estimate the reliability of annotating ci, and therefore Cc, as Ct.
2. For each reference marker gene gjt in Gt, CellClick combines three evidence
   terms:
   - GS(Gc, gjt): similarity between the query marker set Gc and gjt, based on
     cosine similarity of gene expression across all cells and mean expression
     across cell clusters.
   - RES(Gc, gjt | Cc): relative expression specificity of gjt compared with
     Gc in the query cluster Cc, using COSG specificity scores.
   - EAD(Gc, gjt | ci): expression abundance difference of gjt compared with
     the mean expression of Gc in cell ci, transformed by a sigmoid-like
     function with scale factor k = 0.5 by default.
3. CellScore is the average over reference genes in Gt of
   GS(Gc, gjt) * RES(Gc, gjt | Cc) * EAD(Gc, gjt | ci). When gjt is already in
   Gc, the GS, RES, and EAD terms are treated as 1.
4. The violin plot generated by buildCellScorePlot shows the cell score
   distribution for candidate reference cell types. A higher cell score
   distribution indicates that the expression patterns of genes in Gt and Gc
   are more similar, supporting greater reliability for annotating Cc as Ct.
5. The LLM should treat cell scores as comparative evidence for annotation
   validation, not as calibrated probabilities.
"""


SYSTEM_PROMPT = """
You are assisting cell type annotation for single-cell or spatial omics data.
Use only the evidence provided by CellClick. Do not invent expression results,
genes, species, tissue source, or literature claims that are not present in the
input. If evidence is ambiguous, say so and keep the annotation conservative.
Return concise JSON.
"""


def MarkerGeneScores_cal(*args, **kwargs):
    from scripts.adata_processor.annotation_eval import MarkerGeneScores_cal as _impl

    return _impl(*args, **kwargs)


def _split_ref_cell_type(ref_cell_type):
    parts = str(ref_cell_type).split("_", 1)
    if len(parts) == 1:
        return "", parts[0]
    return parts[0], parts[1]


def _json_safe(value):
    if pd.isna(value):
        return None
    if hasattr(value, "item"):
        return value.item()
    return value


def _series_to_gene_records(series, max_genes=50):
    if series is None:
        return []
    records = []
    for gene, score in series.iloc[:max_genes].items():
        records.append({"gene": str(gene), "cosg_score": _json_safe(score)})
    return records


def _candidate_gene_evidence(ref_cell_type, geneWeight, markerSeries, max_genes=20):
    if geneWeight is None or markerSeries is None or ref_cell_type not in geneWeight.index:
        return {
            "reference_genes": [],
            "overlap_genes": [],
            "cosg_unique_genes": [],
            "weighted_overlap_genes": [],
        }

    marker_genes = list(markerSeries.index)
    reference_genes = [gene for gene in geneWeight.columns if geneWeight.loc[ref_cell_type, gene] > 0]
    overlap_genes = [gene for gene in marker_genes if gene in set(reference_genes)]
    cosg_unique_genes = [gene for gene in marker_genes if gene not in set(reference_genes)]

    weighted = []
    for gene in overlap_genes:
        weighted.append(
            {
                "gene": str(gene),
                "mgc": _json_safe(geneWeight.loc[ref_cell_type, gene]),
                "cosg_score": _json_safe(markerSeries.loc[gene]),
                "combined_weight": _json_safe(geneWeight.loc[ref_cell_type, gene] * markerSeries.loc[gene]),
            }
        )
    weighted = sorted(weighted, key=lambda item: item["combined_weight"], reverse=True)

    return {
        "reference_genes": [str(gene) for gene in reference_genes[:max_genes]],
        "overlap_genes": [str(gene) for gene in overlap_genes[:max_genes]],
        "cosg_unique_genes": [str(gene) for gene in cosg_unique_genes[:max_genes]],
        "weighted_overlap_genes": weighted[:max_genes],
    }


def build_marker_gene_score_llm_annotation_evidence(
    marker_gene_scores_cal,
    geneWeight=None,
    markerSeries=None,
    context=None,
    top_n=10,
    max_genes=50,
):
    if isinstance(marker_gene_scores_cal, dict):
        scores = marker_gene_scores_cal.get("scores")
        score_details = marker_gene_scores_cal.get("score_details")
        top_candidate_summary = marker_gene_scores_cal.get("top_candidate_summary") or {}
        geneWeight = geneWeight if geneWeight is not None else marker_gene_scores_cal.get("geneWeight")
        markerSeries = markerSeries if markerSeries is not None else marker_gene_scores_cal.get("markerSeries")
        geneWeightFull = marker_gene_scores_cal.get("geneWeightFull")
        background = marker_gene_scores_cal.get("background")
    else:
        scores = marker_gene_scores_cal
        score_details = None
        top_candidate_summary = {}
        geneWeightFull = None
        background = None

    if scores is None:
        scores = pd.Series(dtype=float)
    if not isinstance(scores, pd.Series):
        scores = pd.Series(scores)

    if score_details is not None and isinstance(score_details, pd.DataFrame) and len(score_details) > 0:
        candidate_df = score_details.head(top_n).copy()
    else:
        candidate_df = None

    evidenceGeneWeight = geneWeightFull if geneWeightFull is not None else geneWeight
    scores = scores.sort_values(ascending=False).iloc[:top_n]
    context = {} if context is None else dict(context)

    candidates = []
    if candidate_df is not None and len(candidate_df) > 0:
        for _, row in candidate_df.iterrows():
            ref_cell_type = row.get("candidate_reference_cell_type")
            if ref_cell_type is None:
                continue
            tissue, cell_type = _split_ref_cell_type(ref_cell_type)
            candidate = row.to_dict()
            candidate["candidate_reference_cell_type"] = str(ref_cell_type)
            candidate["gene_evidence"] = _candidate_gene_evidence(
                ref_cell_type,
                evidenceGeneWeight,
                markerSeries,
                max_genes=max_genes,
            )
            candidate["tissue"] = tissue
            candidate["cell_type"] = cell_type
            candidates.append(candidate)
    else:
        for rank, (ref_cell_type, score) in enumerate(scores.items(), start=1):
            tissue, cell_type = _split_ref_cell_type(ref_cell_type)
            candidate = {
                "rank": rank,
                "ref_cell_type": str(ref_cell_type),
                "tissue": tissue,
                "cell_type": cell_type,
                "score": _json_safe(score),
                "gene_evidence": _candidate_gene_evidence(
                    ref_cell_type,
                    evidenceGeneWeight,
                    markerSeries,
                    max_genes=max_genes,
                ),
            }
            if top_candidate_summary and rank == 1:
                candidate.update(top_candidate_summary)
            candidates.append(candidate)

    if len(candidates) == 0 and len(scores) > 0:
        for rank, (ref_cell_type, score) in enumerate(scores.items(), start=1):
            tissue, cell_type = _split_ref_cell_type(ref_cell_type)
            candidates.append(
                {
                    "rank": rank,
                    "ref_cell_type": str(ref_cell_type),
                    "tissue": tissue,
                    "cell_type": cell_type,
                    "score": _json_safe(score),
                    "gene_evidence": _candidate_gene_evidence(
                        ref_cell_type,
                        evidenceGeneWeight,
                        markerSeries,
                        max_genes=max_genes,
                    ),
                }
            )

    return {
        "context": context,
        "top_cosg_marker_genes": _series_to_gene_records(markerSeries, max_genes=max_genes),
        "candidate_reference_cell_types": candidates,
        "top_candidate_summary": top_candidate_summary,
        "background": background,
    }


