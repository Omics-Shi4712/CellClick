def _extract_text_from_response(response):
    if isinstance(response, str):
        return response
    if isinstance(response, dict):
        if "content" in response:
            return response["content"]
        if "text" in response:
            return response["text"]
    if hasattr(response, "output_text"):
        return response.output_text
    if hasattr(response, "choices"):
        choice = response.choices[0]
        if hasattr(choice, "message") and hasattr(choice.message, "content"):
            return choice.message.content
        if hasattr(choice, "text"):
            return choice.text
    return str(response)


def _parse_json_response(text):
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        match = re.search(r"\{.*\}", text, flags=re.S)
        if match:
            try:
                return json.loads(match.group(0))
            except json.JSONDecodeError:
                pass
    return None


def _call_llm(llm_client, messages, model=None):
    if callable(llm_client):
        kwargs = {"messages": messages}
        if model is not None:
            kwargs["model"] = model
        return llm_client(**kwargs)

    if hasattr(llm_client, "chat") and hasattr(llm_client.chat, "completions"):
        kwargs = {"messages": messages}
        if model is not None:
            kwargs["model"] = model
        return llm_client.chat.completions.create(**kwargs)

    if hasattr(llm_client, "responses"):
        kwargs = {"input": messages}
        if model is not None:
            kwargs["model"] = model
        return llm_client.responses.create(**kwargs)

    raise TypeError("llm_client must be a callable or an OpenAI-compatible client object")


def make_openai_client(api_key=None, base_url=None, timeout=None):
    try:
        from openai import OpenAI
    except ImportError as exc:
        raise ImportError("Install openai to use api_key/base_url directly: pip install openai") from exc

    kwargs = {}
    if api_key is not None:
        kwargs["api_key"] = api_key
    if base_url is not None:
        kwargs["base_url"] = base_url
    if timeout is not None:
        kwargs["timeout"] = timeout
    return OpenAI(**kwargs)


def evaluate_marker_gene_score_annotation(
    marker_gene_scores_cal,
    geneWeight=None,
    markerSeries=None,
    llm_client=None,
    api_key=None,
    base_url=None,
    model=None,
    timeout=None,
    context=None,
    top_n=10,
    max_genes=50,
    standardize=False,
    jaccard_threshold=0.6,
    ols_base_url="https://www.ebi.ac.uk/ols4/api",
    ontology="cl",
    ontology_mapper=None,
):
    prompt = build_marker_gene_score_llm_annotation_prompt(
        marker_gene_scores_cal,
        geneWeight=geneWeight,
        markerSeries=markerSeries,
        context=context,
        top_n=top_n,
        max_genes=max_genes,
    )
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT.strip()},
        {"role": "user", "content": prompt},
    ]

    if llm_client is None and (api_key is not None or base_url is not None):
        llm_client = make_openai_client(api_key=api_key, base_url=base_url, timeout=timeout)

    if llm_client is None:
        result = {
            "messages": messages,
            "prompt": prompt,
            "annotation": None,
            "raw_response": None,
        }
        if standardize:
            result.update(
                _standardize_marker_gene_annotation_result(
                    None,
                    marker_gene_scores_cal,
                    geneWeight=geneWeight,
                    markerSeries=markerSeries,
                    top_n=top_n,
                    max_genes=max_genes,
                    jaccard_threshold=jaccard_threshold,
                    ols_base_url=ols_base_url,
                    ontology=ontology,
                    ontology_mapper=ontology_mapper,
                )
            )
        return result

    raw_response = _call_llm(llm_client, messages, model=model)
    response_text = _extract_text_from_response(raw_response)
    annotation = _parse_json_response(response_text)
    result = {
        "messages": messages,
        "prompt": prompt,
        "annotation": annotation,
        "raw_response": response_text,
    }
    if standardize:
        result.update(
            _standardize_marker_gene_annotation_result(
                annotation,
                marker_gene_scores_cal,
                geneWeight=geneWeight,
                markerSeries=markerSeries,
                top_n=top_n,
                max_genes=max_genes,
                jaccard_threshold=jaccard_threshold,
                ols_base_url=ols_base_url,
                ontology=ontology,
                ontology_mapper=ontology_mapper,
            )
        )
    return result


def _standardize_marker_gene_annotation_result(
    annotation,
    marker_gene_scores_cal,
    geneWeight=None,
    markerSeries=None,
    top_n=10,
    max_genes=50,
    jaccard_threshold=0.6,
    ols_base_url="https://www.ebi.ac.uk/ols4/api",
    ontology="cl",
    ontology_mapper=None,
):
    from scripts.ontology_standardization import standardize_annotation_result

    evidence = build_marker_gene_score_llm_annotation_evidence(
        marker_gene_scores_cal,
        geneWeight=geneWeight,
        markerSeries=markerSeries,
        top_n=top_n,
        max_genes=max_genes,
    )
    standardized = standardize_annotation_result(
        annotation,
        evidence["candidate_reference_cell_types"],
        jaccard_threshold=jaccard_threshold,
        ols_base_url=ols_base_url,
        ontology=ontology,
        mapper=ontology_mapper,
    )
    return {
        "raw_annotation": annotation,
        "standardized_annotation": standardized["standardized_annotation"],
        "merge_report": standardized["merge_report"],
        "top_candidate_summary": evidence.get("top_candidate_summary"),
        "background": evidence.get("background"),
    }


def evaluate_cell_score_annotation(
    cell_score_plot_result=None,
    plotDf=None,
    marker_cosg=None,
    markerDict=None,
    llm_client=None,
    api_key=None,
    base_url=None,
    model=None,
    timeout=None,
    context=None,
    top_n=5,
    max_genes=50,
):
    prompt = build_cell_score_llm_annotation_prompt(
        cell_score_plot_result=cell_score_plot_result,
        plotDf=plotDf,
        marker_cosg=marker_cosg,
        markerDict=markerDict,
        context=context,
        top_n=top_n,
        max_genes=max_genes,
    )
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT.strip()},
        {"role": "user", "content": prompt},
    ]

    if llm_client is None and (api_key is not None or base_url is not None):
        llm_client = make_openai_client(api_key=api_key, base_url=base_url, timeout=timeout)

    if llm_client is None:
        return {
            "messages": messages,
            "prompt": prompt,
            "annotation": None,
            "raw_response": None,
        }

    raw_response = _call_llm(llm_client, messages, model=model)
    response_text = _extract_text_from_response(raw_response)
    return {
        "messages": messages,
        "prompt": prompt,
        "annotation": _parse_json_response(response_text),
        "raw_response": response_text,
    }


